import {
  is_arithmetic,
  type ArrayLiteral,
  type Binary,
  type Call,
  type Case,
  type ComparisonOperator,
  type Expression,
  type Identifier,
  type Index,
  type Interpolation,
  type Member,
  type Unary,
} from './ast.ts'
import {
  emit_array_new,
  emit_get,
  emit_join,
  emit_length,
  emit_pop,
  emit_push,
} from './array_codegen.ts'
import { emit_binary_get, emit_binary_length, emit_binary_slice } from './binary_codegen.ts'
import { builtins } from './builtins.ts'
import type { Types } from './checker.ts'
import type { CheckedInt } from './checked_int.ts'
import type { IrBuilder } from './ir_builder.ts'
import {
  emit_release,
  emit_retain,
  function_symbol,
  ir_param_type,
  ir_return_type,
  ir_type,
  string_constant,
} from './lerta_ir.ts'
import type { Scopes } from './scopes.ts'
import { emit_concat, emit_equals, emit_to_string } from './string_codegen.ts'
import { is_reference_type, type Type } from './types.ts'

const comparison_predicates: Record<ComparisonOperator, string> = {
  '==': 'eq',
  '!=': 'ne',
  '<': 'slt',
  '<=': 'sle',
  '>': 'sgt',
  '>=': 'sge',
}

// A loop variable or a parameter is an SSA value; a `const` or `var` lives in a stack slot.
export type CodegenLocal =
  { kind: 'value'; operand: string; type: Type } | { kind: 'slot'; pointer: string; type: Type }

// Expressions. Each yields an IR operand; a reference-typed one is owned by the consumer.
export class ExpressionGenerator {
  private readonly ir: IrBuilder
  private readonly types: Types
  private readonly checked_int: CheckedInt
  private readonly locals: Scopes<CodegenLocal>
  // Top-level functions, which a call prefers to a builtin of the same name.
  private readonly function_names: Set<string>

  constructor(
    ir: IrBuilder,
    types: Types,
    checked_int: CheckedInt,
    locals: Scopes<CodegenLocal>,
    function_names: Set<string>,
  ) {
    this.ir = ir
    this.types = types
    this.checked_int = checked_int
    this.locals = locals
    this.function_names = function_names
  }

  // Returns the IR operand holding the value; void calls return ''.
  generate(expression: Expression): string {
    switch (expression.kind) {
      case 'string':
        if (this.types.get(expression)!.kind === 'UInt8') {
          return new TextEncoder().encode(expression.value)[0].toString()
        }
        return string_constant(this.ir, expression.value)
      case 'interpolation':
        return this.generate_interpolation(expression)
      case 'integer':
        return expression.value.toString()
      case 'boolean':
        return expression.value ? 'true' : 'false'
      case 'call':
        return this.generate_call(expression)
      case 'unary':
        return this.generate_unary(expression)
      case 'binary':
        return this.generate_binary(expression)
      case 'case':
        return this.generate_case(expression)
      case 'identifier':
        return this.generate_identifier(expression)
      case 'range':
        throw new Error('ranges are only generated by for')
      case 'member':
        return this.generate_property(expression)
      case 'array':
        return this.generate_array(expression)
      case 'index':
        return this.generate_index(expression)
      case 'function':
        throw new Error('functions are only generated at the top level')
    }
  }

  // Arguments are borrowed: the caller releases its temporaries after the call.
  private generate_call(call: Call): string {
    const { callee } = call
    if (callee.kind === 'member') return this.generate_method_call(call, callee)
    if (callee.kind !== 'identifier') throw new Error('only named functions can be called')
    const arg_types = call.args.map((arg) => this.types.get(arg)!)
    const operands = call.args.map((arg) => this.generate(arg))
    const args = operands.map((operand, i) => `${ir_type(arg_types[i])} ${operand}`).join(', ')
    const result = this.function_names.has(callee.name)
      ? this.call_function(callee, args)
      : this.call_builtin(callee.name, arg_types, args)
    call.args.forEach((arg, i) => this.release_if_reference(arg, operands[i]))
    return result
  }

  private call_function(callee: Identifier, args: string): string {
    const type = this.types.get(callee)!
    if (type.kind !== 'function') throw new Error('a called function has a function type')
    const call = `call ${ir_return_type(type.result)} ${function_symbol(callee.name)}(${args})`
    if (type.result.kind === 'void') {
      this.ir.emit(call)
      return ''
    }
    return this.ir.assign(call)
  }

  private call_builtin(name: string, arg_types: Type[], args: string): string {
    const symbol = builtins.get(name)!.runtime_symbol(arg_types)
    const params = arg_types.map(ir_param_type).join(', ')
    this.ir.declare(symbol, `declare void @${symbol}(${params})`)
    this.ir.emit(`call void @${symbol}(${args})`)
    return ''
  }

  // `to_string()` passes on the object's ownership (a String returns itself); the other methods
  // borrow the object and release it after the call, as they do the arguments.
  private generate_method_call(call: Call, member: Member): string {
    const object_type = this.types.get(member.object)!
    const object = this.generate(member.object)
    const { name } = member.name
    if (name === 'to_string') return emit_to_string(this.ir, object, object_type)
    if (name === 'to_int') return this.ir.assign(`zext i8 ${object} to i64`)
    const args = call.args.map((arg) => this.generate(arg))
    const result =
      object_type.kind === 'Array'
        ? this.call_array_method(name, object, object_type.element, args)
        : emit_binary_slice(this.ir, object, args[0], args[1])
    call.args.forEach((arg, i) => this.release_if_reference(arg, args[i]))
    emit_release(this.ir, object)
    return result
  }

  private call_array_method(name: string, array: string, element: Type, args: string[]): string {
    switch (name) {
      case 'push':
        emit_push(this.ir, array, args[0], element)
        return ''
      case 'pop':
        return emit_pop(this.ir, array, element)
      case 'join':
        return emit_join(this.ir, array, args[0])
      default:
        throw new Error(`no array method ${name}`)
    }
  }

  // Each item is pushed, so the array retains it; the item's own reference is then released.
  private generate_array(array: ArrayLiteral): string {
    const type = this.types.get(array)!
    if (type.kind !== 'Array') throw new Error('an array literal has an array type')
    const result = emit_array_new(this.ir, type.element)
    for (const element of array.elements) {
      const value = this.generate(element)
      emit_push(this.ir, result, value, type.element)
      this.release_if_reference(element, value)
    }
    return result
  }

  private generate_index(index: Index): string {
    const object = this.generate(index.object)
    const position = this.generate(index.index)
    const item =
      this.types.get(index.object)!.kind === 'Binary'
        ? emit_binary_get(this.ir, object, position)
        : emit_get(this.ir, object, position, this.types.get(index)!)
    emit_release(this.ir, object)
    return item
  }

  // `s.binary` is the string itself, passing on its ownership; `length` borrows its object.
  private generate_property(member: Member): string {
    const object = this.generate(member.object)
    const object_kind = this.types.get(member.object)!.kind
    if (object_kind === 'String') return object
    const length =
      object_kind === 'Binary' ? emit_binary_length(this.ir, object) : emit_length(this.ir, object)
    emit_release(this.ir, object)
    return length
  }

  private generate_interpolation(interpolation: Interpolation): string {
    const parts = interpolation.parts.map((part) =>
      typeof part === 'string'
        ? string_constant(this.ir, part)
        : emit_to_string(this.ir, this.generate(part), this.types.get(part)!),
    )
    return emit_concat(this.ir, parts)
  }

  // Every expression of a reference type yields an owned reference, which its consumer releases.
  release_if_reference(expression: Expression, operand: string): void {
    if (is_reference_type(this.types.get(expression)!)) emit_release(this.ir, operand)
  }

  private generate_unary(unary: Unary): string {
    const operand = this.generate(unary.operand)
    if (unary.operator === 'not') return this.ir.assign(`xor i1 ${operand}, true`)
    return this.checked_int.apply('-', '0', operand, this.types.get(unary)!)
  }

  private generate_binary(binary: Binary): string {
    if (binary.operator === 'and' || binary.operator === 'or') return this.generate_logical(binary)
    const left = this.generate(binary.left)
    const right = this.generate(binary.right)
    const { operator } = binary
    if (this.types.get(binary.left)!.kind === 'String') {
      if (operator === '+') return emit_concat(this.ir, [left, right])
      const equal = emit_equals(this.ir, left, right)
      return operator === '==' ? equal : this.ir.assign(`xor i1 ${equal}, true`)
    }
    const operand_type = this.types.get(binary.left)!
    if (is_arithmetic(operator)) return this.checked_int.apply(operator, left, right, operand_type)
    const is_byte = operand_type.kind === 'UInt8'
    // UInt8 is ordered as unsigned.
    const predicate = comparison_predicates[operator].replace(/^s/, is_byte ? 'u' : 's')
    return this.ir.assign(`icmp ${predicate} ${ir_type(operand_type)} ${left}, ${right}`)
  }

  // Short-circuit: the right operand is evaluated only when the left one does not decide.
  private generate_logical(binary: Binary): string {
    const left = this.generate(binary.left)
    const left_block = this.ir.current_block
    const right_label = this.ir.fresh_label('logical.right')
    const end_label = this.ir.fresh_label('logical.end')
    const is_and = binary.operator === 'and'
    const [if_true, if_false] = is_and ? [right_label, end_label] : [end_label, right_label]
    this.ir.emit(`br i1 ${left}, label %${if_true}, label %${if_false}`)
    this.ir.start_block(right_label)
    const right = this.generate(binary.right)
    const right_block = this.ir.current_block
    this.ir.emit(`br label %${end_label}`)
    this.ir.start_block(end_label)
    const decided = is_and ? 'false' : 'true'
    return this.ir.assign(`phi i1 [ ${decided}, %${left_block} ], [ ${right}, %${right_block} ]`)
  }

  // Tests the conditions in order; every arm jumps to one end block that merges the values.
  private generate_case(case_expression: Case): string {
    const end_label = this.ir.fresh_label('case.end')
    const incoming: string[] = []
    const generate_arm_value = (value: Expression) => {
      const operand = this.generate(value)
      incoming.push(`[ ${operand}, %${this.ir.current_block} ]`)
      this.ir.emit(`br label %${end_label}`)
    }
    for (const arm of case_expression.arms) {
      const condition = this.generate(arm.condition)
      const arm_label = this.ir.fresh_label('case.arm')
      const next_label = this.ir.fresh_label('case.next')
      this.ir.emit(`br i1 ${condition}, label %${arm_label}, label %${next_label}`)
      this.ir.start_block(arm_label)
      generate_arm_value(arm.value)
      this.ir.start_block(next_label)
    }
    generate_arm_value(case_expression.otherwise)
    this.ir.start_block(end_label)
    const type = this.types.get(case_expression)!
    if (type.kind === 'void') return ''
    return this.ir.assign(`phi ${ir_type(type)} ${incoming.join(', ')}`)
  }

  // Reading a reference from a slot retains it, since every expression yields an owned reference.
  private generate_identifier(identifier: Identifier): string {
    const local = this.locals.lookup(identifier.name)!
    const value =
      local.kind === 'value'
        ? local.operand
        : this.ir.assign(`load ${ir_type(local.type)}, ptr ${local.pointer}`)
    if (is_reference_type(local.type)) emit_retain(this.ir, value)
    return value
  }
}
